"""OPTIONAL integration template following PyPSA's documented FBMC pool model.

This requires an installed and compatible PyPSA+Linopy+LP solver. It is NOT
executed/qualified by the pure NumPy/SciPy tests. It uses a research proxy
FB domain generated by ``examples/run_fbmc_bridge.py``; it is not Core RAM.

python examples/run_fbmc_bridge.py
python examples/pypsa_fbmc_market_template.py

Reference: https://docs.pypsa.org/stable/examples/fbmc-simple-example/
"""
from pathlib import Path
import sys
import numpy as np
import pandas as pd


def main():
    try:
        import pypsa
    except ImportError as e:
        raise SystemExit('Requires optional PyPSA: pip install -e ".[pypsa]"') from e
    base=Path(__file__).resolve().parents[1]
    domain_path=base/'outputs'/'fbmc'/'fbmc_domain_capacity.csv'
    if not domain_path.exists():
        raise SystemExit('First run: python examples/run_fbmc_bridge.py')
    df=pd.read_csv(domain_path).set_index('CNEC_direction')
    zones=['market_zone_A','market_zone_B','market_zone_C']
    n=pypsa.Network()
    n.add('Bus',[*zones,'pool'])
    load=pd.Series([30.,32.,38.],index=zones)
    cost=pd.Series([10.,45.,75.],index=zones)
    n.add('Load',zones,bus=zones,p_set=load)
    n.add('Generator',zones,bus=zones,p_nom=150.,marginal_cost=cost)
    # One market export outlet for each zone. The auxiliary pool is NOT an AC bus.
    n.add('Link',zones,bus0=zones,bus1='pool',p_nom=500.,p_min_pu=-1)
    n.sanitize()
    m=n.optimize.create_model()
    netpos=m['Link-p'].sel(name=zones)
    m.add_constraints(netpos @ df[zones] <= df['RAM_MW'],name='fb_domain_research')
    status=n.optimize.solve_model(log_to_console=False)
    print('Market clearing status:',status)
    print('NET POSITIONS [MW], research FB domain:')
    print(n.links_t.p0.loc[:,zones].round(3).to_string())
    print('PRICE [EUR/MWh]:')
    print(n.buses_t.marginal_price.loc[:,zones].round(3).to_string())
    print('WARNING: synthetic research domain; not valid Core RAM or an operational FBMC simulation.')


if __name__=='__main__':
    main()
